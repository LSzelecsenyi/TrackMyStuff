# Lifted multiply: shadows stay shaded, highlights approach the recency color.
SHADE_WEIGHT = 0.62
SHADE_LIFT = 0.38


def knockout(image: Image.Image) -> Image.Image:
    from collections import deque

    rgba = image.convert("RGBA")
    pixels = rgba.load()
    width, height = rgba.size
    for y in range(height):
        for x in range(width):
            r, g, b, a = pixels[x, y]
            whitest = min(r, g, b)
            if whitest >= 250:
                pixels[x, y] = (r, g, b, 0)
            elif whitest >= 236:
                fade = int(a * (250 - whitest) / 14)
                pixels[x, y] = (r, g, b, max(0, fade))
    # Remove the floor shadow, which stays connected to the paper-white background.
    # Interior highlights are darker and enclosed by the body, so the fill stops there.
    seen = bytearray(width * height)
    queue = deque()

    def consider(x: int, y: int) -> None:
        index = y * width + x
        if seen[index]:
            return
        r, g, b, a = pixels[x, y]
        if a > 0 and min(r, g, b) < 236:
            return
        seen[index] = 1
        queue.append((x, y))

    for x in range(width):
        consider(x, 0)
        consider(x, height - 1)
    for y in range(height):
        consider(0, y)
        consider(width - 1, y)
    while queue:
        x, y = queue.popleft()
        r, g, b, _ = pixels[x, y]
        pixels[x, y] = (r, g, b, 0)
        for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
            if 0 <= nx < width and 0 <= ny < height:
                consider(nx, ny)
    return rgba


def _kotlin_float(value: float) -> str:
    if value == int(value):
        return f"{int(value)}f"
    return f"{value}f"


def generate(model: dict) -> None:
    asset_dir = model["asset_dir"]
    asset_dir.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(model["src"], asset_dir / model["asset_name"])

    root = ET.parse(model["src"]).getroot()
    view_box = [float(part) for part in root.attrib["viewBox"].split()]
    source_width = view_box[2] - view_box[0]
    source_height = view_box[3] - view_box[1]
    split_x = source_width / 2
    image_el = root.find(f".//{SVG}image")
    href = None
    for _key, value in image_el.attrib.items():
        if _key.endswith("href") and value.startswith("data:image"):
            href = value
            break
    if href is None:
        raise SystemExit(f"embedded anatomy image was not found in {model['src'].name}")
    import base64
    import io

    png = base64.b64decode(href.split(",", 1)[1])
    anatomy = knockout(Image.open(io.BytesIO(png)))
    anatomy.save(asset_dir / "anatomy.png", optimize=True)

    paths = []
    for el in root.findall(f".//{SVG}path"):
        pid = el.attrib["id"]
        label = el.attrib.get(f"{INK}label", "")
        data = el.attrib["d"]
        min_x, _, max_x, _ = _bounds(data)
        center_x = (min_x + max_x) / 2
        view = "FRONT" if center_x < split_x else "BACK"
        paths.append((pid, label, view, data))

    ids = [pid for pid, _, _, _ in paths]
    if len(ids) != len(set(ids)):
        raise SystemExit(f"duplicate path ids in {model['src'].name}: {ids}")

    source_name = model["src"].name
    lines = [
        "/*",
        f" * Generated by tools/generate_male_muscle_map.py from {source_name}.",
        " * Path data is the baked Inkscape `d` attribute. Live path effects are not reapplied.",
        " * Do not edit path strings by hand; regenerate from the untouched source SVG.",
        " */",
        "package app.mymusclemap.ui.components.musclemap.artwork",
        "",
        f"internal object {model['object_name']} {{",
        f"    const val SOURCE_FILE = \"{source_name}\"",
        f"    const val ANATOMY_ASSET = \"{model['anatomy_asset']}\"",
        f"    const val SOURCE_WIDTH = {_kotlin_float(source_width)}",
        f"    const val SOURCE_HEIGHT = {_kotlin_float(source_height)}",
        f"    const val SPLIT_X = {_kotlin_float(split_x)}",
        f"    const val FIGURE_WIDTH = {_kotlin_float(split_x)}",
        f"    const val FIGURE_HEIGHT = {_kotlin_float(source_height)}",
        "",
        "    val paths: List<MuscleArtworkPath> = listOf(",
    ]
    for pid, label, view, data in paths:
        literal = json.dumps(data)
        label_literal = json.dumps(label)
        lines.append(
            f"        MuscleArtworkPath(id = {json.dumps(pid)}, inkscapeLabel = {label_literal}, "
            f"view = MuscleMapView.{view}, pathData = {literal}),"
        )
    lines.append("    )")
    lines.append("}")
    lines.append("")
    model["kt_path"].write_text("\n".join(lines), encoding="utf-8")
    print(f"{source_name} paths {len(paths)} split {split_x}")
    for pid, _, view, _ in paths:
        print(f"  {view} {pid}")
    print(f"anatomy {(asset_dir / 'anatomy.png').stat().st_size} bytes")
    if model["preview"]:
        _write_preview(anatomy, paths)
        print("preview", PREVIEW)


def main() -> None:
    for model in MODELS:
        generate(model)


def _bounds(data: str):
    import re

    token = re.compile(r"[MmZzLlHhVvCcSsQqTtAa]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?")
    tokens = token.findall(data)
    i = 0
    cx = cy = 0.0
    sx = sy = 0.0
    cmd = None
    xs = []
    ys = []

    def num():
        nonlocal i
        value = float(tokens[i])
        i += 1
        return value

    def add(x, y):
        xs.append(x)
        ys.append(y)

    while i < len(tokens):
        if re.match(r"[A-Za-z]", tokens[i]):
            cmd = tokens[i]
            i += 1
        rel = cmd.islower()
        kind = cmd.upper()
        if kind == "M":
            x, y = num(), num()
            if rel:
                x += cx
                y += cy
            cx, cy = sx, sy = x, y
            add(cx, cy)
            while i < len(tokens) and not re.match(r"[A-Za-z]", tokens[i]):
                x, y = num(), num()
                if rel:
                    x += cx
                    y += cy
                cx, cy = x, y
                add(cx, cy)
        elif kind == "Z":
            cx, cy = sx, sy
        elif kind == "L":
            x, y = num(), num()
            if rel:
                x += cx
                y += cy
            cx, cy = x, y
            add(cx, cy)
        elif kind == "H":
            x = num()
            if rel:
                x += cx
            cx = x
            add(cx, cy)
        elif kind == "V":
            y = num()
            if rel:
                y += cy
            cy = y
            add(cx, cy)
        elif kind == "C":
            pts = []
            for _ in range(3):
                x, y = num(), num()
                if rel:
                    x += cx
                    y += cy
                pts.append((x, y))
            for x, y in pts:
                add(x, y)
            cx, cy = pts[-1]
        elif kind == "S":
            pts = []
            for _ in range(2):
                x, y = num(), num()
                if rel:
                    x += cx
                    y += cy
                pts.append((x, y))
            for x, y in pts:
                add(x, y)
            cx, cy = pts[-1]
        elif kind == "Q":
            pts = []
            for _ in range(2):
                x, y = num(), num()
                if rel:
                    x += cx
                    y += cy
                pts.append((x, y))
            for x, y in pts:
                add(x, y)
            cx, cy = pts[-1]
        elif kind == "T":
            x, y = num(), num()
            if rel:
                x += cx
                y += cy
            cx, cy = x, y
            add(cx, cy)
        elif kind == "A":
            num()
            num()
            num()
            num()
            num()
            x, y = num(), num()
            if rel:
                x += cx
                y += cy
            cx, cy = x, y
            add(cx, cy)
        else:
            raise SystemExit(f"unsupported {cmd}")
    return min(xs), min(ys), max(xs), max(ys)


def _write_preview(anatomy: Image.Image, paths) -> None:
    import re

    from PIL import ImageDraw

    scale = 0.42
    base = anatomy.resize(
        (int(anatomy.width * scale), int(anatomy.height * scale)),
        Image.Resampling.LANCZOS,
    )
    colors = {
        "pecs": (27, 94, 32),
        "sbd": (211, 47, 47),
        "serratus": (245, 124, 0),
        "obliques_front": (251, 192, 45),
        "obliques_back": (100, 181, 246),
        "upper_back": (27, 94, 32),
        "lats": (102, 187, 106),
        "front_delts": (251, 192, 45),
        "traps_front": (27, 94, 32),
        "tigh_extensors_front": (57, 73, 171),
        "calves_front": (211, 47, 47),
    }
    token = re.compile(r"[MmZzLlHhVvCc]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?")
    overlay = base.copy()
    draw = ImageDraw.Draw(overlay, "RGBA")
    for pid, _, _, data in paths:
        if pid not in colors:
            continue
        contours = _flatten(data, token)
        mask = Image.new("L", overlay.size, 0)
        mask_draw = ImageDraw.Draw(mask)
        for contour in contours:
            pts = [(x * scale, y * scale) for x, y in contour]
            if len(pts) >= 3:
                mask_draw.polygon(pts, fill=255)
        color = colors[pid]
        tint = overlay.copy()
        tint_px = tint.load()
        mask_px = mask.load()
        src_px = base.load()
        for y in range(overlay.height):
            for x in range(overlay.width):
                if mask_px[x, y] == 0:
                    continue
                r, g, b, a = src_px[x, y]
                if a == 0:
                    continue
                lum = (0.299 * r + 0.587 * g + 0.114 * b) / 255
                factor = lum * SHADE_WEIGHT + SHADE_LIFT
                tint_px[x, y] = (
                    int(color[0] * factor),
                    int(color[1] * factor),
                    int(color[2] * factor),
                    255,
                )
        overlay = tint
    PREVIEW.parent.mkdir(parents=True, exist_ok=True)
    overlay.resize((overlay.width, overlay.height), Image.Resampling.LANCZOS).save(PREVIEW)


def _flatten(data: str, token):
    tokens = token.findall(data)
    i = 0
    cx = cy = sx = sy = 0.0
    cmd = None
    contours = []
    current = []

    def num():
        nonlocal i
        value = float(tokens[i])
        i += 1
        return value

    while i < len(tokens):
        if tokens[i].isalpha():
            cmd = tokens[i]
            i += 1
        rel = cmd.islower()
        c = cmd.upper()
        if c == "M":
            x, y = num(), num()
            if rel:
                x += cx
                y += cy
            if current:
                contours.append(current)
            cx = cy = sx = sy = x
            cy = y
            sx, sy = x, y
            current = [(x, y)]
            while i < len(tokens) and not tokens[i].isalpha():
                x, y = num(), num()
                if rel:
                    x += cx
                    y += cy
                cx, cy = x, y
                current.append((cx, cy))
        elif c == "Z":
            current.append((sx, sy))
            cx, cy = sx, sy
        elif c == "L":
            x, y = num(), num()
            if rel:
                x += cx
                y += cy
            cx, cy = x, y
            current.append((cx, cy))
        elif c == "H":
            x = num()
            if rel:
                x += cx
            cx = x
            current.append((cx, cy))
        elif c == "V":
            y = num()
            if rel:
                y += cy
            cy = y
            current.append((cx, cy))
        elif c == "C":
            x1, y1 = num(), num()
            x2, y2 = num(), num()
            x, y = num(), num()
            if rel:
                x1 += cx
                y1 += cy
                x2 += cx
                y2 += cy
                x += cx
                y += cy
            x0, y0 = current[-1]
            for step in range(1, 9):
                t = step / 8
                u = 1 - t
                px = u**3 * x0 + 3 * u**2 * t * x1 + 3 * u * t**2 * x2 + t**3 * x
                py = u**3 * y0 + 3 * u**2 * t * y1 + 3 * u * t**2 * y2 + t**3 * y
                current.append((px, py))
            cx, cy = x, y
        else:
            raise SystemExit(f"unsupported {cmd}")
    if current:
        contours.append(current)
    return contours


if __name__ == "__main__":
    main()
